// Package schemacontract shares reviewed storage policy between explicit
// PostgreSQL upgrades and the legacy development alignment command.
package schemacontract

import (
	"context"
	_ "embed"

	"github.com/jackc/pgx/v5"
)

// SQL contains no business-data rewriting and requires the caller's transaction.
//
//go:embed columns.sql
var columnsSQL string

//go:embed guards.sql
var guardsSQL string

// SQL is the complete forward schema contract.
var SQL = columnsSQL + guardsSQL

// ApplyComplete applies the contract only after the full current schema exists.
// Historical partial fixtures/installations remain owned by their earlier migrations.
func ApplyComplete(ctx context.Context, tx pgx.Tx) error {
	var complete bool
	if err := tx.QueryRow(ctx, `SELECT count(*)=280 FROM information_schema.columns
 WHERE table_schema='public' AND (table_name,column_name) IN (`+targetPairs+`)`).Scan(&complete); err != nil {
		return err
	}
	if !complete {
		return nil
	}
	_, err := tx.Exec(ctx, SQL)
	return err
}

